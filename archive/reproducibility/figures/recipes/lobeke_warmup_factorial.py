"""Causal final-checkpoint effects from the matched Lobeke warm-up factorial."""

from __future__ import annotations

import hashlib
from pathlib import Path

import numpy as np

from experiments.guard.paper.rewards import validate_evaluation_reward_normalization
from reproducibility.figures.statistics import mean_interval

PANELS = (
    ("target_suboptimality", "(a) Target SubOpt", r"$\Delta\,\operatorname{SubOpt}(\hat\mu)$"),
    (
        "averaged_transfer_suboptimality",
        "(b) Averaged Transfer SubOpt",
        r"$\Delta\,\operatorname{SubOpt}(\hat\mu)$",
    ),
    ("target_fisher_error", "(c) Target Fisher error", r"$\Delta$ Fisher error"),
    (
        "self_concordance_distance",
        "(d) Certificate distance",
        r"$\Delta\max_\mu d_\mu$",
    ),
)


def _effect_coordinates(arrays: np.lib.npyio.NpzFile, metric: str) -> str:
    coordinates: list[str] = []
    for multiplier in (3, 12):
        warm = arrays[f"warm_lambda{multiplier}__{metric}"]
        no_warm = arrays[f"no_warm_lambda{multiplier}__{metric}"]
        if warm.shape != (50,) or no_warm.shape != (50,):
            raise ValueError(f"invalid factorial arm shape for {metric}/lambda{multiplier}")
        effect = warm - no_warm
        mean, lower, upper = mean_interval(effect[:, None], confidence_level=0.95)
        half_width = max(float(mean[0] - lower[0]), float(upper[0] - mean[0]))
        coordinates.append(f"({multiplier},{mean[0]:.12g}) +- (0,{half_width:.12g})")
    return " ".join(coordinates)


def render_lobeke_warmup_factorial(provenance: dict[str, object], provenance_path: Path) -> str:
    """Render paired warm-minus-no-warm effects at each matched lambda."""

    if provenance.get("schema_version") != 2:
        raise ValueError("unsupported Lobeke warm-up factorial schema")
    try:
        validate_evaluation_reward_normalization(provenance.get("leader_reward_normalization", {}))
    except ValueError as error:
        raise ValueError("Lobeke warm-up factorial requires unit-interval rewards") from error
    if provenance.get("experiment") != "matched Active IRL warm-up/lambda factorial":
        raise ValueError("unexpected Lobeke warm-up factorial experiment")
    design = provenance.get("design", {})
    if design.get("paired_seeds") != list(range(30_000, 30_050)):
        raise ValueError("Lobeke warm-up factorial has the wrong paired seeds")
    if design.get("warmup_budgets") != [0, 200]:
        raise ValueError("Lobeke warm-up factorial has the wrong warm-up levels")
    if design.get("lambda_information_multipliers") != [3, 12]:
        raise ValueError("Lobeke warm-up factorial has the wrong lambda levels")
    sources = provenance.get("sources", {})
    if sources.get("reference", {}).get("run_id") != "8c4ab05e9b2fe388":
        raise ValueError("unexpected reference run for Lobeke warm-up factorial")
    if not sources.get("swapped", {}).get("run_id"):
        raise ValueError("missing swapped run for Lobeke warm-up factorial")
    if sources.get("swapped_extension", {}).get("run_id") != "2d6a6b2f2d58eebd":
        raise ValueError("missing 30-seed swapped extension for Lobeke warm-up factorial")

    data_path = provenance_path.with_name("data.npz")
    if hashlib.sha256(data_path.read_bytes()).hexdigest() != provenance.get("data_sha256"):
        raise ValueError("Lobeke warm-up factorial data failed its checksum")
    with np.load(data_path, allow_pickle=False) as arrays:
        if not np.array_equal(arrays["seeds"], np.arange(30_000, 30_050)):
            raise ValueError("factorial data and provenance seed sets disagree")
        plots = []
        for index, (metric, title, ylabel) in enumerate(PANELS):
            xlabel = (
                r"xlabel={Information multiplier $\lambda/\eta^2$},"
                if index >= 2
                else "xticklabels={},"
            )
            plots.append(
                rf"""\nextgroupplot[
  title={{{title}}},
  ylabel={{{ylabel}}},
  {xlabel}
  xmin=1.5, xmax=13.5,
  xtick={{3,12}},
  scaled y ticks=true,
  enlarge y limits=0.22
]
\draw[mairlInk!45, densely dashed, line width=0.5pt]
  (axis cs:1.5,0) -- (axis cs:13.5,0);
\addplot[draw=mairlActive, line width=0.8pt, mark=*, mark size=1.8pt,
  error bars/.cd, y dir=both, y explicit]
  coordinates {{{_effect_coordinates(arrays, metric)}}};"""
            )
        rendered_plots = "\n".join(plots)

    return rf"""% Generated by reproducibility.figures.recipes.lobeke_warmup_factorial; do not edit.
\begin{{tikzpicture}}
\begin{{groupplot}}[
  group style={{group size=2 by 2, horizontal sep=1.65cm, vertical sep=1.10cm}},
  mairl axis,
  width=0.455\textwidth,
  height=3.65cm,
  tick label style={{font=\tiny}},
  title style={{font=\small\bfseries}},
  ylabel style={{font=\small}},
  xlabel style={{font=\small}}
]
{rendered_plots}
\end{{groupplot}}
\node[anchor=north, font=\scriptsize, text=mairlMuted]
  at ($(group c1r2.south east)!0.5!(group c2r2.south west)+(0,-0.72cm)$)
  {{Points are paired means over 50 seeds; bars are paired 95\% confidence
    intervals. Negative favors warm-up.}};
\end{{tikzpicture}}
"""
