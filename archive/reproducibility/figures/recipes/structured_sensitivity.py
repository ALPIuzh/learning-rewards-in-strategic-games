"""Compose the two protected structured-game sensitivity panels."""

from __future__ import annotations

from pathlib import Path

from reproducibility.figures.recipes.structured_temperature import (
    render_structured_temperature,
)
from reproducibility.figures.recipes.structured_warmup import render_structured_warmup


def render_structured_sensitivity(
    warmup: dict[str, object],
    warmup_path: Path,
    temperature: dict[str, object],
    temperature_path: Path,
) -> str:
    """Render both sensitivity analyses as one publication figure fragment."""

    warmup_panel = render_structured_warmup(warmup, warmup_path)
    temperature_panel = render_structured_temperature(temperature, temperature_path)
    return rf"""% Generated by reproducibility.figures.recipes.structured_sensitivity; do not edit.
\begin{{tabular}}{{@{{}}c@{{\hspace{{0.55cm}}}}c@{{}}}}
{warmup_panel}
&
{temperature_panel}
\\[0.10cm]
\multicolumn{{2}}{{c}}{{\ref{{structured-sensitivity-legend}}}}
\end{{tabular}}
"""
