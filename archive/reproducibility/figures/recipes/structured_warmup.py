"""TikZ renderer for the protected structured-game warm-up ablation."""

from __future__ import annotations

import hashlib
from pathlib import Path

import numpy as np

from reproducibility.figures.statistics import mean_interval

METHODS = (
    ("active", "Active IRL", "mairlActive"),
    ("fixed_random", "Fixed random", "mairlFixed"),
    ("random_each_round", "Online random", "mairlOnline"),
)
WARMUP_BUDGETS = np.asarray([0, 24, 60, 120, 240, 500, 800, 1000])


def _coordinates(x: np.ndarray, y: np.ndarray, *, floor: float) -> str:
    return " ".join(
        f"({x_value:.8g},{max(floor, y_value):.8g})" for x_value, y_value in zip(x, y, strict=True)
    )


def _plots(values: np.ndarray, *, floor: float, legend: bool) -> str:
    if values.shape != (8, 3, 100) or not np.all(np.isfinite(values)):
        raise ValueError("invalid structured warm-up array")
    fractions = WARMUP_BUDGETS / 1000.0
    offsets = (-0.008, 0.0, 0.008)
    commands: list[str] = []
    for index, ((_method, label, color), offset) in enumerate(
        zip(METHODS, offsets, strict=True)
    ):
        mean, lower, upper = mean_interval(values[:, index, :].T, confidence_level=0.95)
        lower = np.maximum(lower, floor)
        upper = np.maximum(upper, floor)
        shifted = fractions + offset
        for x_value, low, high in zip(shifted, lower, upper, strict=True):
            commands.append(
                rf"\addplot[draw={color}, line width=0.45pt, forget plot] coordinates "
                rf"{{({x_value:.8g},{low:.8g}) ({x_value:.8g},{high:.8g})}};"
            )
        commands.append(
            rf"\addplot[only marks, draw={color}, fill={color}, mark=*, "
            rf"mark size=1.25pt, line width=0.55pt] coordinates "
            rf"{{{_coordinates(shifted, mean, floor=floor)}}};"
        )
        if legend:
            commands.append(rf"\addlegendentry{{{label}}}")
    return "\n".join(commands)


def render_structured_warmup(provenance: dict[str, object], provenance_path: Path) -> str:
    """Validate compact data and render the deployment warm-up ablation."""

    if provenance.get("experiment") != "structured-toy protected warm-up ablation":
        raise ValueError("unexpected structured-game experiment")
    if provenance.get("warmup_budgets") != WARMUP_BUDGETS.tolist():
        raise ValueError("unexpected structured-game warm-up grid")
    if provenance.get("methods") != [method for method, _label, _color in METHODS]:
        raise ValueError("unexpected structured-game methods")
    if provenance.get("seed_policy") != {
        "paired": True,
        "seeds": list(range(82_000, 82_100)),
        "count": 100,
    }:
        raise ValueError("unexpected structured-game protected seeds")
    data_path = provenance_path.with_suffix(".npz")
    if hashlib.sha256(data_path.read_bytes()).hexdigest() != provenance["derived_npz_sha256"]:
        raise ValueError("structured-game derived data failed its checksum")
    with np.load(data_path, allow_pickle=False) as arrays:
        if not np.array_equal(arrays["warmup_budgets"], WARMUP_BUDGETS):
            raise ValueError("structured-game warm-up budgets disagree with provenance")
        subopt = _plots(
            arrays["final__stackelberg_suboptimality"],
            floor=1.0e-5,
            legend=True,
        )

    return rf"""% Generated by reproducibility.figures.recipes.structured_warmup; do not edit.
\begin{{tikzpicture}}
\begin{{axis}}[
  mairl axis,
  title={{(a) Warm-up allocation}},
  width=0.44\textwidth,
  height=4.70cm,
  xmin=-0.02, xmax=1.02,
  xtick={{0,0.25,0.5,0.75,1}},
  xlabel={{Warm-up fraction}},
  ymode=log,
  y tick label style={{font=\tiny, text=mairlMuted}},
  ymin=1e-5, ymax=3e-2,
  ytick style={{draw=none}},
  minor y tick style={{draw=none}},
  ylabel={{Target ${{\operatorname{{SubOpt}}(\hat\mu)}}$}},
  legend to name=structured-sensitivity-legend,
  legend style={{legend columns=3, font=\tiny, row sep=-1pt, column sep=5pt}}
]
\draw[mairlInk, dotted, line width=0.45pt]
  (axis cs:0.12,1e-5) -- (axis cs:0.12,3e-2);
\node[anchor=north west, font=\tiny, text=mairlMuted]
  at (axis cs:0.125,2.3e-2) {{canonical}};
{subopt}
\end{{axis}}
\end{{tikzpicture}}
"""
