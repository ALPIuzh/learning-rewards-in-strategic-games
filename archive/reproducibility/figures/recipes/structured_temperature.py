"""TikZ renderer for structured-game inverse-temperature sensitivity."""

from __future__ import annotations

import hashlib
from pathlib import Path

import numpy as np

from reproducibility.figures.statistics import mean_interval

METHODS = (
    ("active", "Active IRL", "mairlActive"),
    ("fixed_random", "Fixed random", "mairlFixed"),
    ("random_each_round", "Online random", "mairlOnline"),
)
ETA_VALUES = np.asarray([0.5, 0.75, 1.25, 2.0, 3.0])


def _coordinates(x: np.ndarray, y: np.ndarray, *, floor: float) -> str:
    if x.shape != y.shape or not np.all(np.isfinite(y)):
        raise ValueError("invalid structured-temperature coordinates")
    return " ".join(
        f"({x_value:.8g},{max(floor, y_value):.8g})" for x_value, y_value in zip(x, y, strict=True)
    )


def _plots(values: np.ndarray, *, floor: float, legend: bool) -> str:
    if values.shape != (5, 3, 100) or not np.all(np.isfinite(values)):
        raise ValueError("invalid structured-temperature array")
    offsets = (-0.025, 0.0, 0.025)
    commands: list[str] = []
    for index, ((_method, label, color), offset) in enumerate(
        zip(METHODS, offsets, strict=True)
    ):
        mean, lower, upper = mean_interval(values[:, index, :].T, confidence_level=0.95)
        lower = np.maximum(lower, floor)
        upper = np.maximum(upper, floor)
        shifted = ETA_VALUES + offset
        for x_value, low, high in zip(shifted, lower, upper, strict=True):
            commands.append(
                rf"\addplot[draw={color}, line width=0.45pt, forget plot] coordinates "
                rf"{{({x_value:.8g},{low:.8g}) ({x_value:.8g},{high:.8g})}};"
            )
        commands.append(
            rf"\addplot[only marks, draw={color}, fill={color}, mark=*, "
            rf"mark size=1.25pt, line width=0.55pt] coordinates "
            rf"{{{_coordinates(shifted, mean, floor=floor)}}};"
        )
        if legend:
            commands.append(rf"\addlegendentry{{{label}}}")
    return "\n".join(commands)


def render_structured_temperature(
    provenance: dict[str, object],
    provenance_path: Path,
) -> str:
    """Validate the protected export and render deployment sensitivity."""

    if provenance.get("experiment") != ("structured-toy protected inverse-temperature sensitivity"):
        raise ValueError("unexpected structured-temperature experiment")
    if provenance.get("eta_values") != ETA_VALUES.tolist():
        raise ValueError("unexpected structured-temperature grid")
    if provenance.get("methods") != [method for method, _label, _color in METHODS]:
        raise ValueError("unexpected structured-temperature methods")
    if provenance.get("seed_policy") != {
        "paired": True,
        "seeds": list(range(83_000, 83_100)),
        "count": 100,
    }:
        raise ValueError("unexpected structured-temperature protected seeds")
    if provenance.get("lambda_information_rule") != "lambda = eta^2":
        raise ValueError("structured-temperature regularization rule is invalid")
    if provenance.get("warmup_budget") != 120 or provenance.get("total_samples") != 1000:
        raise ValueError("unexpected structured-temperature sample protocol")

    data_path = provenance_path.with_suffix(".npz")
    if hashlib.sha256(data_path.read_bytes()).hexdigest() != provenance["derived_npz_sha256"]:
        raise ValueError("structured-temperature derived data failed its checksum")
    with np.load(data_path, allow_pickle=False) as arrays:
        if not np.array_equal(arrays["eta_values"], ETA_VALUES):
            raise ValueError("structured-temperature eta values disagree with provenance")
        subopt = _plots(
            arrays["final__stackelberg_suboptimality"],
            floor=0.0,
            legend=False,
        )
    return rf"""% Generated by reproducibility.figures.recipes.structured_temperature; do not edit.
\begin{{tikzpicture}}
\begin{{axis}}[
  mairl axis,
  title={{(b) Follower response sharpness}},
  width=0.44\textwidth,
  height=4.70cm,
  xmin=0.45, xmax=3.05,
  xtick={{0.5,0.75,1.25,2,3}},
  xlabel={{Follower inverse temperature $\eta$}},
  ymin=0, ymax=0.0018,
  ytick style={{draw=none}},
  minor y tick style={{draw=none}},
  ylabel={{Target ${{\operatorname{{SubOpt}}(\hat\mu)}}$}}
]
\draw[mairlInk, dotted, line width=0.55pt]
  (rel axis cs:0.3076923,0) -- (rel axis cs:0.3076923,1);
\node[anchor=north east, font=\tiny, text=mairlMuted]
  at (axis cs:1.23,0.00172) {{canonical}};
{subopt}
\end{{axis}}
\end{{tikzpicture}}
"""
