"""Compact TikZ explanation of rewards, patrols, and poachers in Lobeke."""

from __future__ import annotations

import hashlib
from pathlib import Path

import numpy as np

from reproducibility.figures.policy_grid import render_lobeke_map


def _validate_grid(name: str, values: np.ndarray) -> np.ndarray:
    grid = np.asarray(values, dtype=np.float64)
    if grid.shape != (5, 5) or not np.all(np.isfinite(grid)) or np.any(grid < 0):
        raise ValueError(f"{name} must be a finite nonnegative 5-by-5 grid")
    if not np.any(grid > 0):
        raise ValueError(f"{name} must contain at least one positive value")
    return grid


def render_lobeke_environment(provenance: dict[str, object], provenance_path: Path) -> str:
    """Render the appendix environment schematic from its frozen compact export."""

    data_path = provenance_path.with_name("data.npz")
    expected_digest = str(provenance["data_sha256"])
    actual_digest = hashlib.sha256(data_path.read_bytes()).hexdigest()
    if actual_digest != expected_digest:
        raise ValueError("Lobeke environment data checksum does not match provenance")
    with np.load(data_path, allow_pickle=False) as arrays:
        if set(arrays.files) != {"target_value", "patrol_coverage", "poacher_attack"}:
            raise ValueError("unexpected Lobeke environment arrays")
        target_value = _validate_grid("target_value", arrays["target_value"])
        patrol_coverage = _validate_grid("patrol_coverage", arrays["patrol_coverage"])
        poacher_attack = _validate_grid("poacher_attack", arrays["poacher_attack"])

    if not np.isclose(patrol_coverage.sum(), 1.0, atol=1e-10):
        raise ValueError("patrol coverage must sum to one in the one-ranger source deployment")
    if not np.isclose(poacher_attack.sum(), 1.0, atol=1e-10):
        raise ValueError("poacher attack probabilities must sum to one")

    model = provenance["model"]
    if not isinstance(model, dict) or model.get("source_game_is_zero_sum") is not True:
        raise ValueError("the Lobeke source environment must be declared zero-sum")
    base = tuple(float(value) for value in model["ranger_base_position"])
    if len(base) != 2 or not all(0 <= value <= 1 for value in base):
        raise ValueError("invalid normalized ranger-base position")
    centers = (1.55, 6.15, 10.75)
    bottom = 0.18
    maps = (
        render_lobeke_map(
            target_value,
            color="mairlZeroSum",
            center_x_cm=centers[0],
            bottom_y_cm=bottom,
            base_position=base,
            value_max=float(target_value.max()),
        ),
        render_lobeke_map(
            patrol_coverage,
            color="mairlActive",
            center_x_cm=centers[1],
            bottom_y_cm=bottom,
            base_position=base,
            value_max=float(patrol_coverage.max()),
        ),
        render_lobeke_map(
            poacher_attack,
            color="mairlFollower",
            center_x_cm=centers[2],
            bottom_y_cm=bottom,
            base_position=base,
            value_max=float(poacher_attack.max()),
        ),
    )
    return rf"""% Generated by reproducibility.figures.recipes.lobeke_environment; do not edit.
\begin{{tikzpicture}}[font=\small, >=stealth]
\node[font=\scriptsize\bfseries, text=mairlInk] at ({centers[0]:.2f}cm,2.46cm)
  {{(a) Target value}};
\node[font=\scriptsize\bfseries, text=mairlInk] at ({centers[1]:.2f}cm,2.46cm)
  {{(b) Ranger patrol}};
\node[font=\scriptsize\bfseries, text=mairlInk] at ({centers[2]:.2f}cm,2.46cm)
  {{(c) Poacher response}};
{maps[0]}
{maps[1]}
{maps[2]}
\node[font=\tiny, text=mairlMuted] at ({centers[0]:.2f}cm,-0.05cm)
  {{ecological value}};
\node[font=\tiny, text=mairlMuted] at ({centers[1]:.2f}cm,-0.05cm)
  {{patrol distribution}};
\node[font=\tiny, text=mairlMuted] at ({centers[2]:.2f}cm,-0.05cm)
  {{attack probability}};
\draw[->, draw=mairlInk, line width=0.45pt]
  (2.78cm,1.13cm) -- node[above, font=\tiny, text=mairlMuted]
  {{optimize patrol}} (4.92cm,1.13cm);
\draw[->, draw=mairlInk, line width=0.45pt]
  (7.38cm,1.13cm) -- node[above, font=\tiny, text=mairlMuted]
  {{logit response}} (9.52cm,1.13cm);
\end{{tikzpicture}}
"""
