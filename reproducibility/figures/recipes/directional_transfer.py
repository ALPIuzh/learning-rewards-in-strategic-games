"""TikZ renderer for the target-dependent Fisher-transfer diagnostic."""

from __future__ import annotations

import hashlib
from pathlib import Path

import numpy as np

from reproducibility.figures.statistics import mean_interval

METHODS = (
    ("active", "Active IRL", "mairlActive", "*"),
    ("zero_sum_ols", "Zero-sum OLS", "mairlZeroSum", "triangle*"),
    ("follower_ols", "Follower-only OLS", "mairlFollower", "square*"),
)


def _summary(values: np.ndarray) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    mean, lower, upper = mean_interval(values.T, confidence_level=0.95)
    return mean, mean - lower, upper - mean


def _point(x: float, mean: float, radius: float, *, color: str, mark: str, legend: str | None = None) -> str:
    command = (
        rf"\addplot[only marks, draw={color}, fill={color}, mark={mark}, mark size=1.55pt, "
        rf"error bars/.cd, y dir=both, y explicit] coordinates "
        rf"{{({x:.6g},{mean:.8g}) +- (0,{radius:.8g})}};"
    )
    if legend is not None:
        command += rf"\addlegendentry{{{legend}}}"
    return command


def _method_points(values: np.ndarray, *, offsets: np.ndarray, legend: bool) -> str:
    if values.shape != (2, 3, 100) or not np.all(np.isfinite(values)):
        raise ValueError("invalid directional-transfer method values")
    commands: list[str] = []
    for method_index, (_method, label, color, mark) in enumerate(METHODS):
        mean, lower, upper = _summary(values[:, method_index, :])
        for task_index in range(2):
            commands.append(
                _point(
                    task_index + 1 + offsets[method_index],
                    float(mean[task_index]),
                    float(max(lower[task_index], upper[task_index])),
                    color=color,
                    mark=mark,
                    legend=(label if legend and task_index == 0 else None),
                )
            )
    return "\n".join(commands)


def render_directional_transfer(provenance: dict[str, object], provenance_path: Path) -> str:
    """Render coefficient, target-Fisher, and deployment consequences."""

    if provenance.get("experiment") != "zero-sum target-dependent Fisher-transfer diagnostic":
        raise ValueError("unexpected directional-transfer experiment")
    if provenance.get("methods") != [method for method, *_rest in METHODS]:
        raise ValueError("unexpected directional-transfer methods")
    if provenance.get("seed_policy") != {"paired": True, "seeds": list(range(60_000, 60_100)), "count": 100}:
        raise ValueError("unexpected directional-transfer protected seeds")
    selection = provenance.get("selection", {})
    if selection.get("uses_learned_estimates") is not False:
        raise ValueError("directional tasks were not selected independently of estimates")
    if selection.get("uses_method_outcomes") is not False:
        raise ValueError("directional tasks were not selected independently of methods")
    if float(selection.get("observed_policy_l1_distance", 0.0)) < 0.75:
        raise ValueError("directional target policies are insufficiently distinct")

    data_path = provenance_path.with_suffix(".npz")
    if hashlib.sha256(data_path.read_bytes()).hexdigest() != provenance["derived_npz_sha256"]:
        raise ValueError("directional-transfer derived data failed its checksum")
    with np.load(data_path, allow_pickle=False) as arrays:
        coefficient = arrays["coefficient_l2_error"]
        fisher = arrays["fisher_transfer_error"]
        subopt = arrays["stackelberg_suboptimality"]
        if coefficient.shape != (3, 100) or not np.all(np.isfinite(coefficient)):
            raise ValueError("invalid directional coefficient errors")
        coefficient_mean, coefficient_ci_lower, coefficient_ci_upper = mean_interval(
            coefficient.T, confidence_level=0.95
        )
        coefficient_radius = np.maximum(
            coefficient_mean - coefficient_ci_lower, coefficient_ci_upper - coefficient_mean
        )
        coefficient_points = "\n".join(
            _point(index + 1, float(coefficient_mean[index]), float(coefficient_radius[index]), color=color, mark=mark)
            for index, (_method, _label, color, mark) in enumerate(METHODS)
        )
        fisher_points = _method_points(fisher, offsets=np.asarray([-0.16, 0.0, 0.16]), legend=True)
        subopt_points = _method_points(subopt, offsets=np.asarray([-0.16, 0.0, 0.16]), legend=False)

    return rf"""% Generated by reproducibility.figures.recipes.directional_transfer; do not edit.
\begin{{tikzpicture}}
\begin{{groupplot}}[
  group style={{group size=3 by 1, horizontal sep=1.35cm}},
  mairl axis,
  width=0.300\textwidth,
  height=4.55cm,
  ytick style={{draw=none}},
  minor y tick style={{draw=none}}
]
\nextgroupplot[
  title={{(a) Coefficient error}},
  xmin=0.5, xmax=3.5,
  xtick={{1,2,3}},
  xticklabels={{Active,ZS OLS,Follower OLS}},
  x tick label style={{rotate=25,anchor=east,font=\tiny}},
  ymin=0,
  ylabel={{Final $\ell_2$ error}}
]
{coefficient_points}
\nextgroupplot[
  title={{(b) Target Fisher error}},
  xmin=0.5, xmax=2.5,
  xtick={{1,2}},
  xticklabels={{Task 1,Task 2}},
  ymin=0,
  ylabel={{Fisher-weighted error}},
  legend style={{at={{(0.5,-0.30)}}, anchor=north, legend columns=2,
                 font=\tiny, row sep=-1pt, column sep=2pt}}
]
{fisher_points}
\nextgroupplot[
  title={{(c) Target SubOpt}},
  xmin=0.5, xmax=2.5,
  xtick={{1,2}},
  xticklabels={{Task 1,Task 2}},
  ymin=0,
  ylabel={{Final ${{\operatorname{{SubOpt}}(\hat\mu)}}$}}
]
{subopt_points}
\end{{groupplot}}
\end{{tikzpicture}}
"""
