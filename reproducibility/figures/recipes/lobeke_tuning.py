"""Render the complete sensitivity grid directly from per-seed, per-task losses."""

from pathlib import Path

import numpy as np


def render_lobeke_tuning(data_path: Path) -> str:
    with np.load(data_path, allow_pickle=False) as data:
        losses = data["transfer_suboptimality"]
        budgets = data["warmup_budgets"]
        multipliers = data["multipliers"]
        seeds = data["seeds"]
    if losses.shape != (len(budgets), len(multipliers), len(seeds), 100):
        raise ValueError("sensitivity data must contain every cell, seed, and task")
    if not np.isfinite(losses).all() or np.any(losses < 0):
        raise ValueError("sensitivity losses must be finite and nonnegative")
    if np.any(multipliers <= 0) or np.any(np.diff(multipliers) <= 0):
        raise ValueError("multipliers must be positive and increasing")
    means = losses.mean(axis=-1).mean(axis=-1) * 1e4
    maximum = float(np.ceil(means.max() * 2) / 2)
    minimum = float(np.floor(means.min() * 2) / 2)
    maximum = max(maximum, minimum + 0.5)
    cells = []
    for row, column in np.ndindex(means.shape):
        value = means[row, column]
        shade = 100 * (value - minimum) / (maximum - minimum)
        color = "white" if shade > 65 else "mairlInk"
        cells.append(
            rf"\path[draw=white, fill=mairlHeatOne!{shade:.6f}!white] "
            rf"(axis cs:{column - 0.5},{row - 0.5}) rectangle (axis cs:{column + 0.5},{row + 0.5});"
        )
        cells.append(rf"\node[text={color}, font=\small] at (axis cs:{column},{row}) {{{value:.2f}}};")
    body = "\n".join(cells)
    xticks = ",".join(map(str, range(len(multipliers))))
    yticks = ",".join(map(str, range(len(budgets))))
    xlabels = ",".join(f"{v:g}" for v in multipliers)
    ylabels = ",".join(f"{v:g}" for v in budgets)
    return rf"""% Generated by reproducibility.figures.recipes.lobeke_tuning; do not edit.
\begin{{tikzpicture}}
\begin{{axis}}[
  mairl axis, width=0.88\textwidth, height=6cm,
  xmin=-0.5, xmax={len(multipliers) - 0.5}, ymin=-0.5, ymax={len(budgets) - 0.5},
  xtick={{{xticks}}}, xticklabels={{{xlabels}}},
  ytick={{{yticks}}}, yticklabels={{{ylabels}}},
  xlabel={{Information multiplier $\lambda/\eta^2$}}, ylabel={{Warm-up observations}},
  axis line style={{draw=none}}, tick style={{draw=none}}, grid=none,
  colormap={{sensitivity}}{{color(0cm)=(white); color(1cm)=(mairlHeatOne)}},
  point meta min={minimum:g}, point meta max={maximum:g}, colorbar,
  colorbar style={{ylabel={{Mean transfer $\operatorname{{SubOpt}}$ ($10^{{-4}}$)}},
    scaled y ticks=false, width=0.2cm}}
]
\addplot[draw=none, only marks, mark=none, point meta=explicit]
  coordinates {{(0,0) [{minimum:g}] (0,0) [{maximum:g}]}};
{body}
\end{{axis}}
\end{{tikzpicture}}
"""
